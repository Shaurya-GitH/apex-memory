-- apex-memory schema, Postgres, migration 1. The schema_version table records how many migrations ran.
-- The logical tables match ../sqlite/001_schema.sql. Differences: identity columns, COLLATE "C" on text that is
-- compared or sorted (byte order, as in SQLite), plpgsql triggers, and expression GIN indexes for search.

CREATE TABLE meta (key TEXT COLLATE "C" PRIMARY KEY, value TEXT);

CREATE TABLE notes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  path TEXT COLLATE "C" NOT NULL UNIQUE,
  domain TEXT COLLATE "C" NOT NULL,
  title TEXT, status TEXT, meta TEXT,
  summary TEXT,
  catalog_position INTEGER,
  decision_status TEXT, impl_status TEXT, evidence TEXT, verified_at TEXT COLLATE "C",
  version INTEGER NOT NULL DEFAULT 1,
  updated_at TEXT COLLATE "C");

CREATE TABLE sections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  note TEXT COLLATE "C" NOT NULL REFERENCES notes(path) ON UPDATE CASCADE,
  heading TEXT COLLATE "C",
  heading_path TEXT COLLATE "C" NOT NULL,
  level INTEGER,
  position INTEGER NOT NULL,
  body TEXT NOT NULL DEFAULT '',
  generated TEXT,
  version INTEGER NOT NULL DEFAULT 1,
  UNIQUE (note, heading_path));

CREATE TABLE links (
  src_section BIGINT NOT NULL REFERENCES sections(id) ON DELETE CASCADE,
  dst TEXT COLLATE "C" NOT NULL,
  anchor TEXT COLLATE "C" NOT NULL DEFAULT '',
  dst_section BIGINT REFERENCES sections(id) ON DELETE SET NULL,
  PRIMARY KEY (src_section, dst, anchor));
CREATE INDEX links_dst ON links(dst);

CREATE TABLE decisions (
  domain TEXT COLLATE "C" NOT NULL,
  id TEXT COLLATE "C" NOT NULL,
  title TEXT,
  status TEXT NOT NULL CHECK (status IN ('proposed','accepted','superseded','rejected')),
  section BIGINT NOT NULL REFERENCES sections(id) ON DELETE CASCADE,
  decided_at TEXT,
  superseded_by TEXT,
  PRIMARY KEY (domain, id));

CREATE TABLE status_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  domain TEXT COLLATE "C" NOT NULL,
  kind TEXT COLLATE "C" NOT NULL CHECK (kind IN ('state','open','blocker','next')),
  text TEXT NOT NULL, refs TEXT, position INTEGER, updated_at TEXT, closed_at TEXT);

CREATE TABLE sources (
  id TEXT COLLATE "C" PRIMARY KEY,
  kind TEXT CHECK (kind IN ('snapshot','live','transcript','web','owner')),
  ref TEXT, captured_at TEXT,
  verify_live INTEGER NOT NULL DEFAULT 0);

CREATE TABLE note_sources (
  note TEXT COLLATE "C" NOT NULL REFERENCES notes(path) ON UPDATE CASCADE ON DELETE CASCADE,
  source TEXT COLLATE "C" NOT NULL REFERENCES sources(id) ON UPDATE CASCADE,
  PRIMARY KEY (note, source));

CREATE TABLE preferences (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  domain TEXT COLLATE "C",
  text TEXT NOT NULL,
  owner_quote TEXT NOT NULL,
  recorded_by TEXT, run_id TEXT,
  recorded_at TEXT COLLATE "C" NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
  retired_at TEXT);

CREATE TABLE leases (
  section BIGINT PRIMARY KEY REFERENCES sections(id) ON DELETE CASCADE,
  actor TEXT, run_id TEXT NOT NULL,
  expires_at TEXT COLLATE "C" NOT NULL);

CREATE TABLE events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts TEXT COLLATE "C" NOT NULL DEFAULT to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'),
  domain TEXT COLLATE "C", actor TEXT, task_id TEXT, run_id TEXT,
  op TEXT COLLATE "C" NOT NULL,
  refs TEXT, body TEXT);

CREATE FUNCTION events_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'events are append-only';
END $$;
CREATE TRIGGER events_no_update BEFORE UPDATE ON events FOR EACH ROW EXECUTE FUNCTION events_append_only();
CREATE TRIGGER events_no_delete BEFORE DELETE ON events FOR EACH ROW EXECUTE FUNCTION events_append_only();

-- Search: the index expressions must stay identical to FTS in postgres.py ('simple' = no stemming, like FTS5's unicode61).
CREATE INDEX notes_fts ON notes USING gin ((setweight(to_tsvector('simple', coalesce(title, '')), 'A') || setweight(to_tsvector('simple', coalesce(summary, '')), 'B')));
CREATE INDEX sections_fts ON sections USING gin ((setweight(to_tsvector('simple', coalesce(heading, '')), 'A') || setweight(to_tsvector('simple', body), 'B')));
CREATE INDEX events_fts ON events USING gin ((setweight(to_tsvector('simple', op), 'A') || setweight(to_tsvector('simple', coalesce(body, '')), 'B')));
